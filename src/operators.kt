fun main() {
    //arithmetic operators
    var num1 = 10
    var num2 = 5


    println(num1 + num2)
    println(num1 - num2)
    println(num1 * num2)
    println(num1 / num2)
    println(num1 % num2) //Modulus

    // comparison operators
    var x = 80
    var y = 34

    println(x > y) // greater than
    println(x < y) // less than
    println(x >= y) // greater than or equal to
    println(x <= y) // less than or equal to
    println(x == y) //equal to
    println(x != y) // not equal to

    //assignment operators
    var number = 100
    println(number)

    number += 2
    println(number)

    number *= 2
    println(number)

    number /= 2
    println(number)

    number -= 2
    println(number)



    // logical operators - && (and), || (or), ! (not)

    println ( 100 == 50 && 100 > 30)
    println ( 100 == 50 || 100 > 30)
    println ( !(100 == 50 || 100 > 30))




}